// Builds styles/tokens.css from the design system's tokens.json, so Tailwind
// classes can only ever use FreshBliss colours, type, radius and shadow.
//
//   npm run tokens      (also runs before `dev` and `build`)
//
// Output has three parts:
//   1. CSS variables per theme (light = default, dark, contrast), switched with
//      <html data-theme="...">.
//   2. A Tailwind @theme block that REPLACES the default palette, radii and
//      shadows with the tokens (so `bg-blue-500` or `rounded-3xl` do not exist).
//   3. One text-* utility per type style (text-display, text-heading-3, ...).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const tokens = JSON.parse(readFileSync(new URL('../../tokens.json', import.meta.url), 'utf8'));
const outFile = fileURLToPath(new URL('../styles/tokens.css', import.meta.url));

const THEMES = ['light', 'dark', 'contrast'];
const SELECTOR = {
  light: ':root, [data-theme="light"]',
  dark: '[data-theme="dark"]',
  contrast: '[data-theme="contrast"]',
};
const COLOR_SCHEME = { light: 'light', dark: 'dark', contrast: 'light' };

const out = [];
const line = (s = '') => out.push(s);

line('/* GENERATED by scripts/build-tokens.mjs from ../tokens.json. Do not edit by hand. */');
line();

// ---- 1. theme variables ----
for (const theme of THEMES) {
  line(`${SELECTOR[theme]} {`);
  line(`  color-scheme: ${COLOR_SCHEME[theme]};`);
  for (const t of tokens.color.tokens) line(`  --fb-${t.name}: ${t.value[theme]};`);
  for (const t of tokens.shadow.tokens) line(`  --fb-${t.name}: ${t.value[theme]};`);
  line('}');
  line();
}

// ---- 2. Tailwind theme (strict: defaults are wiped first) ----
line('@theme inline {');
line('  --color-*: initial;');
for (const t of tokens.color.tokens) line(`  --color-${t.name}: var(--fb-${t.name});`);
line();
line('  --font-*: initial;');
for (const [name, stack] of Object.entries(tokens.type.families)) line(`  --font-${name}: ${stack};`);
line();
line('  --radius-*: initial;');
for (const t of tokens.radius.tokens) line(`  --radius-${t.name.replace('radius-', '')}: ${t.value};`);
line();
line('  --shadow-*: initial;');
for (const t of tokens.shadow.tokens) line(`  --shadow-${t.name.replace('shadow-', '')}: var(--fb-${t.name});`);
line('}');
line();

// ---- 3. type styles ----
// Each style carries its own family, so `text-heading-2` is Georgia and
// `text-body` is Inter, with no second class needed.
const SIZE_OVERRIDE = {
  // The token lists 72px but its usage says "fluid in source: clamp(40px,6vw,72px)".
  display: 'clamp(40px, 6vw, 72px)',
};
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    line(`@utility text-${s.name} {`);
    line(`  font-family: var(--font-${group.family});`);
    line(`  font-size: ${SIZE_OVERRIDE[s.name] ?? s.fontSize};`);
    line(`  line-height: ${s.lineHeight};`);
    line(`  font-weight: ${s.fontWeight};`);
    if (s.letterSpacing) line(`  letter-spacing: ${s.letterSpacing};`);
    if (s.name === 'label') line('  text-transform: uppercase;');
    line('}');
    line();
  }
}

// ---- layout ----
const max = tokens.layout.tokens.find((t) => t.name === 'container-max').value;
const gutter = tokens.spacing.tokens.find((t) => t.name === 'space-24').value;
line('/* Page container: container-max wide, space-24 gutters. */');
line('@utility fb-container {');
line(`  max-width: calc(${max} + 2 * ${gutter});`);
line('  margin-inline: auto;');
line(`  padding-inline: ${gutter};`);
line('}');

writeFileSync(outFile, out.join('\n') + '\n');
console.log(`tokens.css written (${tokens.color.tokens.length} colours, ${tokens.type.groups.flatMap((g) => g.styles).length} type styles)`);
